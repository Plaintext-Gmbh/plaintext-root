package ch.plaintext.flyway;

import org.junit.jupiter.api.DisplayName;
import org.junit.jupiter.api.Test;

import java.io.IOException;
import java.nio.file.Files;
import java.nio.file.Path;
import java.util.ArrayList;
import java.util.LinkedHashMap;
import java.util.List;
import java.util.Map;
import java.util.regex.Matcher;
import java.util.regex.Pattern;
import java.util.stream.Stream;

import static org.junit.jupiter.api.Assertions.assertFalse;
import static org.junit.jupiter.api.Assertions.assertTrue;

/**
 * Zustandsbericht 29.08.2026, Massnahme 13: Leitplanke ueber ALLE Flyway-Migrationen des
 * root-Reactors ({@code <modul>/src/main/resources/db/migration/V*.sql}).
 *
 * <ul>
 *   <li><b>Dateiname</b> {@code V<epoch>__<beschreibung>.sql} — die Nummer kommt aus
 *       {@code ./getflywaynr} (Unix-Sekunden), damit Module sich nicht in die Quere kommen.</li>
 *   <li><b>Versionsnummer reactorweit eindeutig.</b> Zwei Module lieferten dieselbe
 *       {@code V1774038471__create_branding_logo_table.sql} (plaintext-root-flyway und
 *       plaintext-admin-settings, identischer Inhalt). Flyway hat das nur deshalb nicht bemerkt,
 *       weil der Classpath-Scanner gleichnamige Ressourcen zusammenfaellt — eine abweichende
 *       Zeile in einer der Kopien haette einen Checksum-Konflikt beim Start ergeben. Die Kopie
 *       im Flyway-Modul ist entfernt; die Tabelle gehoert zu {@code BrandingLogo} in settings.</li>
 *   <li><b>PostgreSQL-Syntax.</b> Die Apps laufen nur auf {@code jdbc:postgresql}; H2-/HSQLDB-/
 *       MySQL-Idiome (Denylist unten) fallen sonst erst beim Deploy auf.</li>
 * </ul>
 *
 * @author info@plaintext.ch
 * @since 2026
 */
@DisplayName("Flyway-Migrationen des Reactors")
class FlywayMigrationenTest {

    private static final Pattern DATEINAME = Pattern.compile("^V(\\d+)__[A-Za-z0-9_]+\\.sql$");

    /** Nicht-PostgreSQL-Idiome; {@code IDENTITY} ist nur als {@code ... AS IDENTITY} PostgreSQL. */
    private static final Pattern FREMDE_SYNTAX = Pattern.compile(
            "\\bSET\\s+DATABASE\\b|\\bCREATE\\s+(?:MEMORY|CACHED)\\s+TABLE\\b|\\bLONGVARCHAR\\b"
                    + "|\\bAUTO_INCREMENT\\b|\\bENGINE\\s*=|\\bMODIFY\\s+COLUMN\\b|\\bNVARCHAR\\b"
                    + "|\\bTINYINT\\b|\\bDATETIME\\b|\\bCLOB\\b|\\bBLOB\\b|`|(?<!\\bAS\\s)\\bIDENTITY\\b",
            Pattern.CASE_INSENSITIVE);

    private static final Pattern SQL_KOMMENTAR = Pattern.compile("--[^\\n]*");

    @Test
    void denylistErkenntFremdeSyntaxUndLaesstPostgresDurch() {
        assertTrue(FREMDE_SYNTAX.matcher("id BIGINT AUTO_INCREMENT PRIMARY KEY").find());
        assertTrue(FREMDE_SYNTAX.matcher("id BIGINT IDENTITY PRIMARY KEY").find());
        assertTrue(FREMDE_SYNTAX.matcher("body CLOB").find());
        assertFalse(FREMDE_SYNTAX.matcher("id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY").find());
        assertFalse(FREMDE_SYNTAX.matcher("body TEXT NOT NULL, created TIMESTAMP").find());
    }

    @Test
    void dateinamenVersionenUndSyntaxAllerMigrationen() throws IOException {
        Map<String, List<String>> versionen = new LinkedHashMap<>();
        List<String> fehler = new ArrayList<>();
        int anzahl = 0;

        for (Path datei : migrationen()) {
            anzahl++;
            String name = datei.getFileName().toString();
            String kurz = datei.getParent().getParent().getParent().getParent().getParent().getParent()
                    .getFileName() + "/" + name;
            Matcher m = DATEINAME.matcher(name);
            if (!m.matches()) {
                fehler.add(kurz + " : Dateiname entspricht nicht V<nummer>__<beschreibung>.sql");
                continue;
            }
            versionen.computeIfAbsent(m.group(1), k -> new ArrayList<>()).add(kurz);
            String sql = SQL_KOMMENTAR.matcher(Files.readString(datei)).replaceAll("");
            Matcher fremd = FREMDE_SYNTAX.matcher(sql);
            if (fremd.find()) {
                fehler.add(kurz + " : keine PostgreSQL-Syntax: '" + fremd.group() + "'");
            }
        }
        versionen.forEach((version, dateien) -> {
            if (dateien.size() > 1) {
                fehler.add("Version " + version + " mehrfach: " + dateien);
            }
        });

        assertTrue(anzahl >= 1, "Positivkontrolle: keine Migration gefunden — Reactor-Wurzel nicht erkannt?");
        assertTrue(fehler.isEmpty(), () -> fehler.size() + " Befund(e):\n  " + String.join("\n  ", fehler));
    }

    /** Alle {@code V*.sql} unter {@code <reactor>/<modul>/src/main/resources/db/migration}. */
    private static List<Path> migrationen() throws IOException {
        Path reactor = reactorWurzel();
        List<Path> dateien = new ArrayList<>();
        try (Stream<Path> module = Files.list(reactor)) {
            for (Path modul : module.filter(Files::isDirectory).sorted().toList()) {
                Path ordner = modul.resolve("src/main/resources/db/migration");
                if (!Files.isDirectory(ordner)) {
                    continue;
                }
                try (Stream<Path> sqls = Files.list(ordner)) {
                    sqls.filter(p -> p.getFileName().toString().endsWith(".sql")).sorted().forEach(dateien::add);
                }
            }
        }
        return dateien;
    }

    private static Path reactorWurzel() throws IOException {
        Path dir = Path.of(System.getProperty("user.dir")).toAbsolutePath();
        for (int i = 0; i < 8 && dir != null; i++) {
            Path pom = dir.resolve("pom.xml");
            if (Files.isRegularFile(pom) && Files.readString(pom).contains("<modules>")) {
                return dir;
            }
            dir = dir.getParent();
        }
        throw new IllegalStateException("Keine Reactor-Wurzel oberhalb von " + System.getProperty("user.dir"));
    }
}
