-- Tabelle fuer gehashe Magic-Link-Einmal-Tokens (SHA-256, nie Klartext in DB)
CREATE TABLE IF NOT EXISTS MAGIC_LINK_TOKEN (
    ID            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    TOKEN_HASH    VARCHAR(64)  NOT NULL UNIQUE,
    USERNAME      VARCHAR(255) NOT NULL,
    MANDAT        VARCHAR(100) NOT NULL,
    ISSUED_AT     TIMESTAMP    NOT NULL,
    EXPIRES_AT    TIMESTAMP    NOT NULL,
    CONSUMED_AT   TIMESTAMP
);
CREATE INDEX IF NOT EXISTS IX_MAGIC_LINK_TOKEN_USERNAME ON MAGIC_LINK_TOKEN (USERNAME);
CREATE INDEX IF NOT EXISTS IX_MAGIC_LINK_TOKEN_EXPIRES  ON MAGIC_LINK_TOKEN (EXPIRES_AT);
