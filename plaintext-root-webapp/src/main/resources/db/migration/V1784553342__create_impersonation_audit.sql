-- Auditierbare Historie von Admin-Impersonation (wer hat wann wen impersoniert) -- vorher gab es
-- nur log.info, keine abfragbare/persistente Quelle.
CREATE TABLE IF NOT EXISTS IMPERSONATION_AUDIT (
    ID               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ADMIN_USER_ID    BIGINT       NOT NULL,
    ADMIN_USERNAME   VARCHAR(255) NOT NULL,
    TARGET_USER_ID   BIGINT       NOT NULL,
    TARGET_USERNAME  VARCHAR(255) NOT NULL,
    STARTED_AT       TIMESTAMP    NOT NULL,
    ENDED_AT         TIMESTAMP,
    SESSION_ID       VARCHAR(255)
);
CREATE INDEX IF NOT EXISTS IX_IMPERSONATION_AUDIT_ADMIN  ON IMPERSONATION_AUDIT (ADMIN_USER_ID);
CREATE INDEX IF NOT EXISTS IX_IMPERSONATION_AUDIT_TARGET ON IMPERSONATION_AUDIT (TARGET_USER_ID);
