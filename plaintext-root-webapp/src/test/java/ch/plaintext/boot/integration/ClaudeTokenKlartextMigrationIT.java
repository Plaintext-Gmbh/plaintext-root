package ch.plaintext.boot.integration;

import ch.plaintext.testsupport.EmbeddedPg;
import org.junit.jupiter.api.Test;
import org.springframework.beans.factory.annotation.Autowired;
import org.springframework.boot.test.context.SpringBootTest;
import org.springframework.core.io.FileSystemResource;
import org.springframework.jdbc.core.JdbcTemplate;
import org.springframework.jdbc.datasource.init.ResourceDatabasePopulator;
import org.springframework.test.context.ActiveProfiles;
import org.springframework.test.context.DynamicPropertyRegistry;
import org.springframework.test.context.DynamicPropertySource;

import javax.sql.DataSource;
import java.nio.charset.StandardCharsets;
import java.security.MessageDigest;
import java.util.HexFormat;
import java.util.List;
import java.util.Map;

import static org.junit.jupiter.api.Assertions.assertEquals;
import static org.junit.jupiter.api.Assertions.assertNull;

/**
 * Card 1449 S-12: the migration empties the cleartext of the Claude automation token and leaves
 * the hash alone; the token stays valid through the hash. A row WITHOUT hash (app-prod, 13.10.2026:
 * both rows) first gets the hash from its cleartext — the same computation as
 * {@code ApiTokenHasher.sha256Hex} — and then loses the cleartext as well.
 *
 * <p>The migration belongs to {@code plaintext-admin-requirements}, which this webapp does not
 * include (the consumer apps do). The test therefore builds the table in the shape the module's
 * migrations leave it, applies the script from the module's source tree and then looks the token up
 * the way {@code ClaudeAutomationService} does canonically: by its SHA-256 hash
 * ({@code findByApiTokenHash}). That a hash-only row validates is pinned in
 * {@code ClaudeAutomationServiceTest.validateTokenMatchesViaStoredHashWithoutPlaintext}.
 */
@SpringBootTest(webEnvironment = SpringBootTest.WebEnvironment.MOCK)
@ActiveProfiles("test")
class ClaudeTokenKlartextMigrationIT {

    private static final String SKRIPT = "../plaintext-admin-requirements/src/main/resources/db/migration/"
            + "V1791865750__clear_plaintext_claude_api_token.sql";

    @DynamicPropertySource
    static void configureProperties(DynamicPropertyRegistry registry) {
        EmbeddedPg.registrieren(registry, "claudetokenklartextmigrationit");
    }

    @Autowired
    private DataSource dataSource;

    /** Same as {@code ApiTokenHasher.sha256Hex}: SHA-256 over UTF-8, lowercase hex. */
    private static String sha256Hex(String s) throws Exception {
        return HexFormat.of().formatHex(MessageDigest.getInstance("SHA-256").digest(s.getBytes(StandardCharsets.UTF_8)));
    }

    private static List<String> mandantUeberHash(JdbcTemplate jdbc, String token) throws Exception {
        return jdbc.queryForList("SELECT mandat FROM anforderung_api_settings WHERE api_token_hash = ?",
                String.class, sha256Hex(token));
    }

    @Test
    void klartextWirdGeleert_tokenGiltUeberDenHashWeiter() throws Exception {
        JdbcTemplate jdbc = new JdbcTemplate(dataSource);
        // Columns as left by V820629636 + V820774656 + V1783625400 of plaintext-admin-requirements.
        jdbc.execute("CREATE TABLE IF NOT EXISTS anforderung_api_settings (id BIGINT GENERATED BY DEFAULT AS IDENTITY"
                + " PRIMARY KEY, api_token VARCHAR(500), claude_automation_enabled BOOLEAN, mandat VARCHAR(100) UNIQUE,"
                + " api_token_hash VARCHAR(64))");
        String mitHash = "token-mit-hash-" + System.nanoTime();
        String ohneHash = "token-ohne-hash-" + System.nanoTime();
        jdbc.update("INSERT INTO anforderung_api_settings (mandat, api_token, api_token_hash) VALUES (?, ?, ?)",
                "k1449a", mitHash, sha256Hex(mitHash));
        jdbc.update("INSERT INTO anforderung_api_settings (mandat, api_token, api_token_hash) VALUES (?, ?, NULL)",
                "k1449b", ohneHash);

        new ResourceDatabasePopulator(new FileSystemResource(SKRIPT)).execute(dataSource);

        Map<String, Object> a = jdbc.queryForMap(
                "SELECT api_token, api_token_hash FROM anforderung_api_settings WHERE mandat = 'k1449a'");
        assertNull(a.get("api_token"), "Klartext muss geleert sein");
        assertEquals(sha256Hex(mitHash), a.get("api_token_hash"), "Hash bleibt unberuehrt");
        assertEquals(List.of("k1449a"), mandantUeberHash(jdbc, mitHash), "Token gilt ueber den Hash weiter");

        Map<String, Object> b = jdbc.queryForMap(
                "SELECT api_token, api_token_hash FROM anforderung_api_settings WHERE mandat = 'k1449b'");
        assertEquals(sha256Hex(ohneHash), b.get("api_token_hash"), "Hash muss aus dem Klartext ergaenzt sein");
        assertNull(b.get("api_token"), "Klartext muss auch ohne vorherigen Hash geleert sein");
        assertEquals(List.of("k1449b"), mandantUeberHash(jdbc, ohneHash), "Token gilt ueber den neuen Hash");
    }
}
